/**
 * 标准化方言地区名称
 * @param region 原始地区名称
 * @returns 标准化后的方言名称
 */
export function standardizeDialectRegion(region: string): string {
  if (!region || typeof region !== 'string') {
    return region;
  }

  // 去除空格和特殊字符
  const cleanRegion = region.trim().replace(/[\s\-_]/g, '');
  
  // 直接映射
  if (DIALECT_MAPPING[cleanRegion]) {
    return DIALECT_MAPPING[cleanRegion];
  }
  
  // 模糊匹配
  const lowerRegion = cleanRegion.toLowerCase();
  for (const [key, value] of Object.entries(DIALECT_MAPPING)) {
    if (key.toLowerCase().includes(lowerRegion) || lowerRegion.includes(key.toLowerCase())) {
      return value;
    }
  }
  
  // 关键词匹配
  for (const [standardRegion, keywords] of Object.entries(REGION_KEYWORDS)) {
    for (const keyword of keywords) {
      if (cleanRegion.includes(keyword) || keyword.includes(cleanRegion)) {
        // 根据标准地区返回对应的标准方言名
        const standardDialect = Object.entries(DIALECT_MAPPING).find(([_, value]) => 
          value.includes(standardRegion)
        );
        if (standardDialect) {
          return standardDialect[1];
        }
      }
    }
  }
  
  // 如果没有匹配到，返回原始值
  return region;
}

/**
 * 批量标准化方言地区数据
 * @param data 包含region字段的数据数组
 * @returns 标准化后的数据数组
 */
export function standardizeDialectData<T extends { region: string }>(data: T[]): T[] {
  return data.map(item => ({
    ...item,
    region: standardizeDialectRegion(item.region)
  }));
}

/**
 * 获取所有支持的标准方言列表
 * @returns 标准方言名称数组
 */
export function getSupportedDialects(): string[] {
  const uniqueDialects = new Set(Object.values(DIALECT_MAPPING));
  return Array.from(uniqueDialects).sort();
}

/**
 * 检查是否为有效的方言地区
 * @param region 地区名称
 * @returns 是否为有效方言
 */
export function isValidDialectRegion(region: string): boolean {
  const standardized = standardizeDialectRegion(region);
  return standardized !== region || Object.values(DIALECT_MAPPING).includes(region);
}